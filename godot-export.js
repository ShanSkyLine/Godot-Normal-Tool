const ZIP_CRC_TABLE=(()=>{const a=new Uint32Array(256);for(let i=0;i<256;i++){let c=i;for(let k=0;k<8;k++)c=c&1?0xedb88320^(c>>>1):c>>>1;a[i]=c>>>0;}return a;})();
function zipCRC(data){let crc=0xffffffff;for(const b of data)crc=ZIP_CRC_TABLE[(crc^b)&255]^(crc>>>8);return (crc^0xffffffff)>>>0;}
function zipStored(files){
  if(files.length>65535)throw Error('ZIP entry limit');
  const encoder=new TextEncoder(),locals=[],central=[];let offset=0;
  for(const f of files){
    if(!f.name||f.name.includes('..')||f.name.startsWith('/'))throw Error('Invalid ZIP path');
    const name=encoder.encode(f.name),data=typeof f.data==='string'?encoder.encode(f.data):new Uint8Array(f.data),crc=zipCRC(data);
    if(name.length>65535||data.length>0xffffffff)throw Error('ZIP size limit');
    const local=new Uint8Array(30+name.length),l=new DataView(local.buffer);
    l.setUint32(0,0x04034b50,true);l.setUint16(4,20,true);l.setUint16(6,0x800,true);l.setUint16(12,33,true);l.setUint32(14,crc,true);l.setUint32(18,data.length,true);l.setUint32(22,data.length,true);l.setUint16(26,name.length,true);local.set(name,30);locals.push(local,data);
    const header=new Uint8Array(46+name.length),c=new DataView(header.buffer);
    c.setUint32(0,0x02014b50,true);c.setUint16(4,20,true);c.setUint16(6,20,true);c.setUint16(8,0x800,true);c.setUint16(14,33,true);c.setUint32(16,crc,true);c.setUint32(20,data.length,true);c.setUint32(24,data.length,true);c.setUint16(28,name.length,true);c.setUint32(42,offset,true);header.set(name,46);central.push(header);offset+=local.length+data.length;
  }
  const size=central.reduce((s,c)=>s+c.length,0);if(offset+size>0xffffffff)throw Error('ZIP size limit');
  const end=new Uint8Array(22),e=new DataView(end.buffer);e.setUint32(0,0x06054b50,true);e.setUint16(8,files.length,true);e.setUint16(10,files.length,true);e.setUint32(12,size,true);e.setUint32(16,offset,true);
  return new Blob([...locals,...central,end],{type:'application/zip'});
}
function godotPNG(canvas){return new Promise((resolve,reject)=>canvas.toBlob(blob=>blob?blob.arrayBuffer().then(resolve,reject):reject(Error('PNG encoding failed')),'image/png'));}
async function godotPackageFiles(snapshot,encode=godotPNG){
  const files=[],names=snapshot.frames.map((_,i)=>'frame_'+String(i).padStart(4,'0'));let w=1,h=1;
  for(let i=0;i<snapshot.frames.length;i++){
    const {source,normal}=snapshot.frames[i],name=names[i];
    if(source.width!==normal.width||source.height!==normal.height)throw Error('Frame/normal size mismatch');
    w=Math.max(w,source.width);h=Math.max(h,source.height);
    files.push({name:`asset/${name}_diffuse.png`,data:await encode(source)},{name:`asset/${name}_normal.png`,data:await encode(normal)},{name:`asset/${name}_material.tres`,data:godotTres(name)});
  }
  if(!names.length)throw Error('No frames');
  if(names.length>1)files.push({name:'asset/animation.tres',data:godotSpriteFrames(names,snapshot.fps)});
  files.push({name:'asset/lights.gd',data:godotLightsScript(snapshot.lights,Math.max(w,h))},{name:'asset/demo.tscn',data:godotScene(names[0],names.length>1)},{name:'project.godot',data:godotProject(w,h)},{name:'README.txt',data:godotReadme()});
  return files;
}
