function godotNumber(value,fallback=0){const n=Number(value);return Number.isFinite(n)?n:fallback;}
function godotLightsScript(lights=App.lights,size=128){
  const radius=Math.max(16,godotNumber(size,128)), configs=lights.filter(l=>l.enabled).map(l=>
    `\t{"color": ${hexToGdColor(/^#[0-9a-f]{6}$/i.test(l.color)?l.color:'#ffffff')}, "energy": ${Math.max(0,godotNumber(l.intensity,1))}, "position": Vector2(${godotNumber(l.x)*radius}, ${-godotNumber(l.y)*radius}), "height": ${Math.max(0,godotNumber(l.z))*radius}}`);
  return `extends Node2D
# Generated by NormEngine 0.8.0. Attach to a Node2D at the sprite's centre.
# Godot's point lighting approximates the browser's directional preview.
# Shadow casting needs LightOccluder2D geometry authored in your project.
const LIGHT_SETTINGS = [
${configs.join(',\n')}
]
var _generated_lights: Array[PointLight2D] = []

func _ready() -> void:
\tsetup_lights()

func setup_lights() -> void:
\t# Safe to call again: replace only lights created by this script.
\tfor old_light in _generated_lights:
\t\tif is_instance_valid(old_light):
\t\t\tremove_child(old_light)
\t\t\told_light.queue_free()
\t_generated_lights.clear()
\tvar gradient := Gradient.new()
\tgradient.offsets = PackedFloat32Array([0.0, 1.0])
\tgradient.colors = PackedColorArray([Color(1, 1, 1, 1), Color(0, 0, 0, 1)])
\tvar light_texture := GradientTexture2D.new()
\tlight_texture.width = 256
\tlight_texture.height = 256
\tlight_texture.gradient = gradient
\tlight_texture.fill = GradientTexture2D.FILL_RADIAL
\tlight_texture.fill_from = Vector2(0.5, 0.5)
\tlight_texture.fill_to = Vector2(0.5, 0.0)
\tfor settings in LIGHT_SETTINGS:
\t\tvar light := PointLight2D.new()
\t\tlight.texture = light_texture
\t\tlight.texture_scale = ${radius*8/256}
\t\tlight.color = settings["color"]
\t\tlight.energy = settings["energy"]
\t\tlight.position = settings["position"]
\t\tlight.height = settings["height"]
\t\tlight.shadow_enabled = false
\t\tadd_child(light)
\t\t_generated_lights.append(light)
`;
}
