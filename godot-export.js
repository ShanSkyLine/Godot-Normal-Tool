function godotTres(name){
  return `[gd_resource type="CanvasTexture" load_steps=3 format=3]\n\n[ext_resource type="Texture2D" path="${name}_diffuse.png" id="1"]\n[ext_resource type="Texture2D" path="${name}_normal.png" id="2"]\n\n[resource]\ndiffuse_texture = ExtResource("1")\nnormal_texture = ExtResource("2")\nspecular_color = Color(1, 1, 1, 1)\nspecular_shininess = 0.45\n`;
}
function godotSpriteFrames(names,fps){
  return `[gd_resource type="SpriteFrames" load_steps=${names.length+1} format=3]\n\n${names.map((n,i)=>`[ext_resource type="Texture2D" path="${n}_material.tres" id="${i+1}"]`).join('\n')}\n\n[resource]\nanimations = [{\n"frames": [${names.map((_,i)=>`{ "duration": 1.0, "texture": ExtResource("${i+1}") }`).join(', ')}],\n"loop": true,\n"name": &"default",\n"speed": ${Math.max(1,Math.min(120,godotNumber(fps,12)))}\n}]\n`;
}
